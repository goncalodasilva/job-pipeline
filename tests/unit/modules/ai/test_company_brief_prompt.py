HEADINGS = (
    "what_they_do",
    "products",
    "size_and_location",
    "recent_news",
    "culture",
    "other",
)
ROOT = Path(__file__).resolve().parents[4]
AI_FIXTURES = ROOT / "tests/fixtures/ai/company_brief"
GOLDEN = ROOT / "tests/fixtures/prompts/company_brief"
TASK = "company_brief"
SOURCE = "https://example.test/about"
GOLDEN_CONTEXT = {
    "company": "Fictional Orchard",
    "website": "https://orchard.example.test",
    "industry": "Gardening",
}


def resolve_brief(data, urls):
    # Imported when a test runs, so a missing module fails each test, not the collection.
    return importlib.import_module("app.domain.company_brief").resolve_brief(data, urls)


def _library():
    return PromptLibrary(ROOT / "prompts")


def _schema():
    return dict(_library().load(TASK).output_schema)


def _executor(fake):
    return TaskExecutor(
        provider=fake,
        prompts=_library(),
        settings=AIProviderSettings,
        provider_defaults={"fast": "fake-fast", "thorough": "fake-thorough"},
    )


async def _run(fake, context=None, company_id="company-example"):
    payload = json.dumps(GOLDEN_CONTEXT if context is None else context, ensure_ascii=False)
    return await _executor(fake).run_task(
        TASK,
        {"context": payload, "company_id": company_id},
        NotCancelled(),
        meter=RecordingMeter(),
    )


def _fake(*responses):
    fake = FakeAIProvider(web_search=True)
    fake.script(TASK, *responses)
    return fake


def _section(**change):
    base = {
        "heading": "what_they_do",
        "text": "Plans delivery routes.",
        "source_url": SOURCE,
        "source_date": None,
    }
    return {"sections": [{**base, **change}]}



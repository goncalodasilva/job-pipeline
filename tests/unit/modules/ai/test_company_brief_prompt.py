# --- the schema ------------------------------------------------------------------------------


def test_company_brief_schema_is_closed_and_the_heading_enum_matches_the_domain():
    schema = _schema()
    assert schema["type"] == "object" and schema["additionalProperties"] is False
    assert schema["required"] == ["sections"]
    assert open_objects(schema) == []
    sections = schema["properties"]["sections"]
    assert sections["type"] == "array" and sections["maxItems"] == 6
    item = sections["items"]
    assert item["additionalProperties"] is False
    assert set(item["required"]) == {"heading", "text", "source_url", "source_date"}
    assert tuple(item["properties"]["heading"]["enum"]) == HEADINGS
    assert HEADINGS == importlib.import_module("app.domain.company_brief").HEADINGS
    assert item["properties"]["text"]["maxLength"] == 600


def test_company_brief_schema_accepts_an_empty_list_and_a_stated_date():
    jsonschema.validate({"sections": []}, _schema())
    jsonschema.validate(_section(source_date="March 2024"), _schema())
    jsonschema.validate(_section(source_date=None), _schema())



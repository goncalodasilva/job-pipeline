"""The ``company_brief`` task: prompt, schema and the checks on its answer (M8.3 part B; spec 3.1,
3.3, 3.6, 3.7; ADR-124 items 2 to 4; add-ai-task).

The assumed interface:

- ``prompts/company_brief/prompt.md`` version 2, task ``company_brief``, default tier ``thorough``,
  inputs ``[context, company_id]``, ``untrusted_inputs: [context]``. ``context`` is ONE JSON text
  with the company's name, website and industry (keys ``company``, ``website``, ``industry``); the
  user text wraps it once as ``<untrusted_document source="company" id="{{company_id}}">``. No
  fact, job text, CV text or personal detail is an input, so none can be in a request.
- ``prompts/company_brief/schema.json``: a closed object ``{"sections": [...]}`` of at most 6
  sections; each is closed and requires ``heading`` (a closed enum, the six words of
  ``app.domain.company_brief.HEADINGS``), ``text`` (1 to 600 characters, no control, line-separator
  or bidirectional-mark character), ``source_url`` (an http or https url without whitespace, at
  most 2000 characters) and ``source_date`` (null, or 1 to 100 characters without those
  characters). An empty list is valid: no reliable source, no section.
- ``TaskSpec("company_brief", kind="summary", allow_web_search=True, max_searches=5)``: a plain
  summary, so the system text carries no honesty notice.
- The golden files ``tests/fixtures/prompts/company_brief/golden_system.txt`` and
  ``golden_user.txt`` are generated by the implementer from the first reviewed render of
  ``GOLDEN_CONTEXT`` below and company id ``company-example``.
"""


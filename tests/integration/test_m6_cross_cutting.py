def test_personal_scan_catches_planted_values(tmp_path: Path) -> None:
    """Control: each kind of value planted in a request is found; a clean request is clean."""
    with exporting_app(tmp_path) as desk:
        strings, photo = saved_personal(desk)
    for value in strings:
        assert find_personal(f"before {value} after", strings, photo), value
    assert find_personal("phone 4420 7946 0555 here", strings, photo) == ["phone digits"]
    assert find_personal("call 020 7946 0555 now", strings, photo) == ["phone digits"]
    assert find_personal("call (0)20-7946-0555", strings, photo) == ["phone digits"]
    assert find_personal("dear ZARA,", strings, photo), "case does not hide the first name"
    assert find_personal("Dear Zara,", strings, photo), "the first name alone is found"
    assert find_personal("ZARA.MARKER@EXAMPLE.ORG", strings, photo), "case does not hide a value"
    # The surfaces scan: case-insensitive, and it keeps every settings row but the details.
    surfaces = Surfaces()
    surfaces.add("settings row 0 column key", "personal_details")
    surfaces.add("settings row 0 column value", f'{{"name": "{NAME}"}}')
    surfaces.add("settings row 1 column key", "ai_provider")
    surfaces.add("settings row 1 column value", "ok")
    surfaces.add("log", "clean line")
    assert len(personal_leaks(surfaces, strings, photo)) >= 1
    other = without_personal_details_row(surfaces)
    assert personal_leaks(other, strings, photo) == []
    assert [w for w, _ in other.texts if w.startswith("settings row 1 ")]
    surfaces.add("settings row 1 column extra", NAME.upper())
    assert personal_leaks(without_personal_details_row(surfaces), strings, photo)
    surfaces.add("log line", "national 020 7946 0555 and zara")
    assert any(
        "log line" in leak
        for leak in personal_leaks(without_personal_details_row(surfaces), strings, photo)
    )
    for needle in photo_needles(photo):
        assert find_personal(f"data: {needle}", strings, photo), needle[:12]
    clean = "Planned 60 delivery routes a week with a team of 3. Zephyr, Lisbon, 2019."
    assert find_personal(clean, strings, photo) == []



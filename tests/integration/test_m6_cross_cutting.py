def made_text(number: int) -> str:
    return f"Handled fictional harbour task number {number} for the team."


def _sixty_line_cv(fact_numbers: list[int], texts: dict[int, str]) -> dict[str, Any]:
    sections = ("summary", "experience", "education", "skills")
    units = [
        {
            "kind": "content",
            "section": sections[n % len(sections)],
            "role": None,
            "text": texts[number],
            "fact_ids": [f"F{number}@1"],
            "added_details": [],
        }
        for n, number in enumerate(fact_numbers[:60])
    ]
    return {"units": units}



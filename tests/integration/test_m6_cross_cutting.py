def settled(desk: Exporting, task_type: str, count: int = 1) -> list[dict[str, Any]]:
    def ended() -> list[dict[str, Any]] | None:
        found = desk.rows("SELECT * FROM tasks WHERE type=? ORDER BY rowid", (task_type,))
        ok = len(found) >= count and all(row["status"] in TERMINAL for row in found)
        return found if ok else None

    return wait_until(ended, timeout=DEADLINE, message=f"{task_type} ended")


def drive_extract_cv(desk: Exporting) -> None:
    run = desk.r.run
    run.finished(run.paste(CV_TEXT))


def drive_refine_fact(desk: Exporting) -> None:
    fact = desk.r.target()
    desk.r.answer_with("ok")
    desk.r.started(fact.id)


def drive_intake(task_type: str) -> Callable[[Exporting], None]:
    def drive(desk: Exporting) -> None:
        desk.cv_ready("intake-seed", template=False)  # confirmed facts, so the fit is assessed
        response = desk.post_fields("/inbox/intake", {"text": distinct_text("greenhouse")})
        assert response.status_code == 200, response.text[:300]
        for row in settled(desk, task_type):
            assert row["status"] == "succeeded", (task_type, row["error"])

    return drive



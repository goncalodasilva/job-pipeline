"""M6.12 cross-cutting checks: AC-M1.4 extended to document text, personal details and the photo,
and the response-time budget of the Tailoring tab (spec 2.9 rule 13, 2.11, 2.13, 3.3; ADR-106).

What is planted, all fictional:

- the personal details and photo that ``tests/export_pages.Exporting.save_contact`` saves (the
  values of ``tests/details_pages``: a name, email, phone, location, two links and a generated
  PNG whose stored file name is generated by code);
- document text: a marker typed into a CV line and into a letter paragraph by the person, and the
  text of every unit the generated documents hold.

They may be stored only where they belong (the personal details in the ``settings`` row, the
document text in the ``document*`` tables) and must never reach a surface that is only about
tasks and diagnostics: every log record as it was made (before redaction), the log files, the
console, the rows of ``tasks``, ``usage_records``, ``provider_usage_snapshots`` and
``budget_notices``, the event stream (headers and frames) and the error text a person sees when a
generation fails. The failures are forced through a malformed AI answer and a provider that
raises with the text in its detail and in a chained cause, an unexpected exception, a timeout, an
export that fails with the text in its message, and an unexpected error while the step is drawn.
For those last two the check is on the response body (the in-process client does not go through
uvicorn's logger, so what a server log would hold for them is not checked here). The scan of the
personal values ignores case and covers every settings row except ``personal_details``.

``test_personal_scan_catches_planted_values`` is the scan's own control for the AI-request check.
The personal details and the photo are filled in by code (spec 2.9 rule 13) and must reach no AI
request, for every task in ``TASK_SPECS``.

No network, no sleeps, ``FrozenClock`` where the harness uses one.
"""


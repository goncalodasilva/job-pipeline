# The last ten digits of the phone, so a national format (0 prefix instead of +44) is caught too.
PHONE_TAIL = "".join(c for c in PHONE if c.isdigit())[-10:]


def personal_leaks(surfaces: Surfaces, strings: list[str], photo: bytes) -> list[str]:
    """Where in ``surfaces`` a personal value or the photo shows, ignoring case (the shared
    ``Surfaces.leaks`` compares exactly). Reports the place and the label, never the text."""
    return [
        f"{label} in {where}"
        for where, text in surfaces.texts
        for label in find_personal(text, strings, photo)
    ]


def without_personal_details_row(surfaces: Surfaces) -> Surfaces:
    """The surfaces minus the cells of the ``settings`` row whose key is ``personal_details``,
    the one place the details are stored by design. Other settings rows stay in the scan."""
    own = {
        match.group(1)
        for where, text in surfaces.texts
        if (match := re.fullmatch(r"settings row (\d+) column key", where))
        and text == "personal_details"
    }
    assert own, "the personal_details settings row was not collected"
    kept = [
        (where, text)
        for where, text in surfaces.texts
        if not any(where.startswith(f"settings row {n} ") for n in own)
    ]
    return Surfaces(texts=kept)


def photo_needles(photo: bytes) -> list[str]:
    """The photo in the forms it could be pasted in: base64 at each alignment (from the start and
    from the middle of the file), hex, and as raw characters."""
    assert len(photo) > 120, "the generated photo is too small to be searched for"
    needles: list[str] = []
    for start in (0, len(photo) // 2):
        for shift in range(3):
            chunk = photo[start + shift : start + shift + 45]
            needles.append(base64.b64encode(chunk).decode())
            needles.append(base64.urlsafe_b64encode(chunk).decode())
    needles.append(photo[:24].hex())
    needles.append(photo[len(photo) // 2 : len(photo) // 2 + 24].hex())
    needles.append(photo[len(photo) // 2 : len(photo) // 2 + 16].decode("latin-1"))
    return needles


def find_personal(text: str, strings: list[str], photo: bytes) -> list[str]:
    """Labels of what ``text`` holds of the personal values and the photo."""
    lowered = text.lower()
    found = [f"value {i}" for i, value in enumerate(strings) if value.lower() in lowered]
    digits = "".join(c for c in text if c.isdigit())
    if PHONE_TAIL in digits:
        found.append("phone digits")
    found.extend(f"photo form {i}" for i, n in enumerate(photo_needles(photo)) if n in text)
    return found


def request_text(request: Any) -> str:
    return "\n".join(
        (
            request.task,
            request.prompt_id,
            str(request.prompt_version),
            request.system,
            request.user,
            json.dumps(request.output_schema, ensure_ascii=False),
            json.dumps(request.output_schema),
            request.model,
        )
    )



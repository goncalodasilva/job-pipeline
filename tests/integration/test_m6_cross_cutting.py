def blob_tables(desk: Exporting, snippet: bytes) -> set[str]:
    found: set[str] = set()
    with desk.db.transaction() as conn:
        names = [r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")]
        for name in names:
            quoted = '"' + name.replace('"', '""') + '"'
            for row in conn.execute(f"SELECT * FROM {quoted}"):  # noqa: S608 - names from sqlite_master
                if any(isinstance(c, bytes) and snippet in c for c in row):
                    found.add(name)
    return found


def test_document_text_personal_details_and_photo_never_in_logs_task_rows_or_events(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    with (
        patch("app.main.UuidIdFactory", SequentialIdFactory),
        watched(tmp_path, monkeypatch, capsys) as watch,
    ):
        run = watch.run
        desk = Exporting(Refining(run))
        portal, opened = open_events(watch)
        with opened as stream:
            frames = [portal.call(stream.next_chunk)]

            # 1. A CV and a letter with the person's own words in them, exported and sent.
            app = desk.cv_ready("doc-job")
            strings, photo = saved_personal(desk)
            desk.generate(app.id, "ok")
            lines = desk.units(desk.current_version_id(app.id), removed=False)
            line = next(row for row in lines if row["kind"] == "content")
            edited = desk.edit(app.id, line["id"], f"{line['text'].rstrip('.')} {CV_EDIT}.")
            assert edited.status_code == 200, edited.text[:300]
            approved = desk.approve_now(app.id)
            assert approved.status_code == 200, approved.text[:300]
            desk.draft(app.id, "ok")
            paragraph = desk.units(desk.current_letter_id(app.id), removed=False)[0]
            worded = f"{paragraph['text'].rstrip('.')} {LETTER_EDIT}."
            assert desk.edit_paragraph(app.id, paragraph["id"], worded).status_code == 200
            assert desk.approve_letter_now(app.id).status_code == 200
            exported = desk.export_ok(app.id)
            watch.surfaces.add_headers("export", exported)
            for row in desk.exports(app.id):
                downloaded = desk.download(app.id, row["id"])
                assert downloaded.status_code == 200
                watch.surfaces.add_headers("download", downloaded)  # the file is the document
            applied = desk.mark_applied(app.id)
            assert applied.status_code == 200, applied.text[:300]
            watch.surfaces.add_headers("applied", applied)
            drawer = watch.get(f"/applications/{app.id}/detail")
            assert drawer.status_code == 200
            watch.surfaces.add_headers("drawer", drawer)

            # 2. Failures with the text in the answer, the detail, the chained cause and the
            #    message of an unexpected error.
            second = desk.cv_ready("doc-job-2")
            everything = " ".join([*DOC_MARKERS, *strings])
            original = run.spy.run
            run.spy.script(TAILOR_CV, ScriptedResponse(raw_text=f"not json {everything} {{"))
            desk.generate(second.id, None, status="failed")
            run.spy.script(
                DRAFT_COVER_LETTER, ScriptedResponse(raw_text=f"not json {everything} {{")
            )
            desk.draft(second.id, None, status="failed")

            async def network(request: object, cancel: object) -> object:
                raise NetworkUnavailable(detail=everything) from RuntimeError(everything)

            async def unexpected(request: object, cancel: object) -> object:
                raise RuntimeError(f"unexpected {everything}")

            async def timeout(request: object, cancel: object) -> object:
                raise TimeoutError(f"timeout {everything}")

            for behaviour in (network, unexpected, timeout):
                monkeypatch.setattr(run.spy, "run", behaviour)
                desk.generate(second.id, None, status="failed")
                desk.draft(second.id, None, status="failed")
            monkeypatch.setattr(run.spy, "run", original)

            # 3. What a person sees about those failures.
            for shown in (desk.step3(second.id), desk.step4(second.id)):
                assert shown.status_code == 200
                watch.surfaces.add_headers("failed step", shown)
                for status_line in _status_lines(shown.text):
                    watch.surfaces.add("failed step status line", status_line)
            for path in ("/tasks/panel", "/tasks/indicator", "/settings/usage"):
                shown = watch.get(path)
                assert shown.status_code == 200, path
                watch.surfaces.add(f"{path} body", shown.text)
                watch.surfaces.add_headers(path, shown)

            # An unexpected error in a route: what is checked is the response body the person
            # gets (the in-process client does not go through uvicorn's logger).
            async def export_fails(aid: str) -> str:
                raise RuntimeError(f"export {everything}")

            monkeypatch.setattr(run.app.state.exports, "export", export_fails)
            broken = desk.export(app.id)
            assert broken.status_code == 500
            watch.surfaces.add("failed export body", broken.text)
            watch.surfaces.add_headers("failed export", broken)

            # Same: the body of the 500 page is what is scanned.
            def view_fails(*args: object, **kwargs: object) -> object:
                raise RuntimeError(f"view {everything}")

            monkeypatch.setattr(run.app.state.documents, "view", view_fails)
            broken = desk.step3(second.id)
            assert broken.status_code == 500
            watch.surfaces.add("unexpected error body", broken.text)
            watch.surfaces.add_headers("unexpected error", broken)

            # 4. The stream, through the last task.
            states = final_states(run)
            assert list(states.values()).count("failed") >= 8, states
            frames.append(read_until_final(portal, stream, states))
            watch.surfaces.add("event stream headers", repr(stream.headers))
            watch.surfaces.add("event stream frames", b"".join(frames).decode("utf-8", "replace"))

        # Control: the flows stored the values, and only where they belong.
        for value in (NAME, EMAIL, PHONE, LOCATION, LINKS[0], strings[-1]):
            assert_stored_only_in(run, value, frozenset({"settings"}))
        assert blob_tables(desk, photo[:40]) == set(), "the photo is a file, not a row"
        assert (run.data_dir / "assets" / strings[-1]).read_bytes() == photo
        for marker in DOC_MARKERS:
            assert_stored_only_in(run, marker, DOCUMENT_TABLES)
        assert "document_units" in tables_containing(run, CV_EDIT)
        assert "document_units" in tables_containing(run, LETTER_EDIT)
        unit_texts = [
            row["text"]
            for row in run.rows("SELECT DISTINCT text FROM document_units")
            if len(row["text"]) >= 25
        ]
        assert len(unit_texts) >= 4, unit_texts
        failed = {r["error"] for r in run.rows("SELECT error FROM tasks WHERE error IS NOT NULL")}
        assert "InvalidModelOutput" in failed, failed

    # Personal details are saved in the ``settings`` row ``personal_details`` by design: that one
    # row is not a diagnostic surface for them. Every other surface, including the other settings
    # rows, is scanned, ignoring case. The document text is scanned over all of them.
    other = without_personal_details_row(watch.surfaces)
    assert other.texts, "the scan saw nothing"
    leaked = personal_leaks(other, strings, photo)
    assert not leaked, "personal data leaked:\n" + "\n".join(leaked)
    lowered = Surfaces(texts=[(where, text.lower()) for where, text in watch.surfaces.texts])
    lowered.assert_clean(tuple(t.lower() for t in (*DOC_MARKERS, *unit_texts)))
    assert any(t[0].startswith("settings row") for t in watch.surfaces.texts)


def _status_lines(page: str) -> list[str]:

    return [
        html.unescape(line) for line in re.findall(r'role="(?:status|alert)"[^>]*>([^<]*)<', page)
    ]


